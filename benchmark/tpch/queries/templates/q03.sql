SELECT
    l_orderkey,
    l_extendedprice,
    l_discount,
    o_orderdate,
    o_shippriority
FROM
    customer,
    orders,
    lineitem
WHERE
    c_mktsegment = 'BUILDING'
    AND c_custkey = o_custkey
    AND l_orderkey = o_orderkey
    AND o_orderdate < '1995-03-15'
    AND l_shipdate > '1995-03-15'
ORDER BY
    revenue DESC,
    o_orderdate
LIMIT 10;
